//! 个股概念题材：MAC（通达信扩展行情）在线源 + 本地缓存。
//!
//! 为什么不用本地 `block_gn.dat`：那份是**通达信客户端**的板块文件，本机这份停在
//! 2022-08-24（内容只有「固态电池 / 芯片 / MCU芯片」这类当年题材，没有「AI智能体」
//! 「DeepSeek概念」等近两年题材）。MAC 的板块数据是**在线**的：2026-11-02 实测
//! 000338 返回 28 个板块，含 AI智能体（880732）、DeepSeek概念（880978）、储能（880730）。
//!
//! 数据流：
//! - **全量刷新**：`0x1231` 取板块清单（概念/地区/风格三类）→ `0x122C` 逐板块取成分股
//!   → 反向建「股票 → 板块」映射 → 落 `data/tdx/concepts_cache.json`；
//! - **按需补漏**：缓存里没有这只股票时，`0x1218` 单股问一次（实测 42ms），写回缓存；
//! - **读路径**：`tags.rs` 优先用本模块；本模块失败才回退本地 `block_gn.dat`（2022 旧数据，
//!   来源会显式标注，不冒充新数据）。
//!
//! 刷新节奏：**每周第一次启动刷一次**。判据是日历周——根 `ts` 早于本周一 00:00
//! （本地时区）即过期，启动检查一次、过期才后台重算（与热度/扫描缓存同一套机制）；
//! 同一周内无论重启多少次都不再出网，概念/地区/风格整周用同一份缓存。
//! 风格块（type=5）随这条节奏走，不再有独立的 30 分钟快周期：厂商按自有节奏重算的
//! 那类标签最多滞后到上次刷新，界面上的「抓取时间」如实显示、不冒充实时。
//! 缓存里没有的个股仍走 `0x1218` 单股按需补漏（写回不动根 `ts`）。
//!
//! 三条不变量（都是踩过的坑，改动时别破）：
//! 1. **缓存键恒为 6 位裸码**：入参先过 `cache_key` 归一化再查、再写。带前/后缀的
//!    代码（`sh600519` / `600519.SH`）若不归一，会必然 miss 并把非规范键写进文件；
//! 2. **根 `ts` 只由全量刷新写**：它既是 `stale()` 的判据，也是界面上的「抓取时间」。
//!    单股补漏沿用旧根 `ts`，只把自己的时刻记在条目第 4 位——否则一次补漏就能把
//!    下一次全量刷新整整数地推迟，并让 6000 只股票冒充刚抓的；
//! 3. **非个股代码（`0x1218` 返回 0 行）不进缓存文件**：走带 TTL 的内存负缓存。
//!    写进文件会让 `stocks` 虚增、把「无题材」和「查不到」混为一谈；完全不记则每次
//!    请求都要重开一条 TCP（实测 200ms）。
//!
//! 文件拆分（2026-11-07）：
//! - `cache`：本地状态与缓存文件（快照/周判据/负缓存/标签拆分），可离线单测；
//! - `source`：MAC 连接、单股补漏、全量刷新、启动刷新。

